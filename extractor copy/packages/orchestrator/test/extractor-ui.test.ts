import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { chromium, type Browser } from 'playwright';
import { expect, it } from 'vitest';
import { createOrchestratorServer } from '../src/server.js';

it('keeps the full grouped, color-coded inventory after an interaction', async () => {
  const directory = await mkdtemp(join(tmpdir(), 'nexus-ui-'));
  let targetBrowser: Browser;
  const server = createOrchestratorServer({ managerDependencies: { artifactsRoot: directory, launchBrowser: async () => { targetBrowser = await chromium.launch(); return targetBrowser; } } });
  const uiBrowser = await chromium.launch();
  try {
    const address = await server.listen(0);
    const page = await uiBrowser.newPage({ viewport: { width: 1600, height: 1000 } });
    page.setDefaultTimeout(5000);
    const errors: string[] = [];
    page.on('pageerror', (error) => errors.push(error.message));
    await page.goto(address.url);
    await page.getByRole('textbox', { name: 'Website URL' }).fill(`${address.url}/fixtures/dom-inventory.html`);
    await page.getByRole('button', { name: 'Load & Extract' }).click();
    await page.locator('.component-tree .element-label').filter({ hasText: /^Name$/ }).waitFor();
    expect(await page.getByRole('heading', { name: 'Interactions & changes' }).count()).toBe(1);
    expect(await page.getByText('Execution Agent', { exact: true }).count()).toBe(0);
    expect(await page.getByRole('button', { name: /model settings/i }).count()).toBe(0);
    const currentState = page.locator('.state-tab.is-selected');
    const controlLabels = () => currentState.locator('.component-tree .element-label').allTextContents();
    const initialLabels = await controlLabels();
    expect(initialLabels).toContain('Name');
    expect(initialLabels).toContain('Change');
    expect(initialLabels).toContain('Closed shadow button');
    expect(initialLabels).toContain('Frame name');
    expect(await page.locator('.dom-inventory, .dom-entry').count()).toBe(0);
    expect(await currentState.locator('.element-row > summary .element-selector').count()).toBe(0);
    const nameDot = currentState.locator('.component-tree .element-row').filter({ has: page.locator('.element-label', { hasText: /^Name$/ }) }).locator('.type-dot');
    expect(await nameDot.evaluate((element) => getComputedStyle(element).color)).toBe('rgb(22, 163, 74)');
    const target = targetBrowser!.contexts()[0]!.pages()[0]!;
    await target.getByRole('button', { name: 'Change', exact: true }).click();
    await expect.poll(async () => page.locator('.activity-entry').filter({ hasText: 'Click Change' }).count(), { timeout: 5000 }).toBeGreaterThan(0);
    await expect.poll(async () => page.locator('.state-tab').count(), { timeout: 5000 }).toBeGreaterThan(1);
    await expect.poll(controlLabels, { timeout: 5000 }).toEqual(expect.arrayContaining(initialLabels));
    expect(await nameDot.evaluate((element) => getComputedStyle(element).color)).toBe('rgb(22, 163, 74)');
    await page.getByRole('textbox', { name: 'Website URL' }).fill(`${address.url}/fixtures/semantic-display.html`);
    await page.getByRole('button', { name: 'Load & Extract' }).click();
    const username = currentState.locator('.element-label').filter({ hasText: /^Username$/ });
    const password = currentState.locator('.element-label').filter({ hasText: /^Password$/ });
    await username.waitFor({ state: 'visible' });
    await password.waitFor({ state: 'visible' });
    expect(await currentState.locator('.group-heading > span').allTextContents()).toEqual(expect.arrayContaining(['Header', 'Login', 'Filter']));
    expect(await currentState.locator('.collection-table tbody tr').count()).toBe(4);
    expect(await currentState.locator('.collection-table').innerText()).toContain('Backpack');
    expect(await page.locator('.dom-inventory, .dom-entry').count()).toBe(0);
    expect(await currentState.locator('.element-row > summary').allTextContents()).not.toEqual(expect.arrayContaining([expect.stringMatching(/<\/?(?:html|body|div|script|style)\b/)]));
    const latestTarget = targetBrowser!.contexts()[0]!.pages()[0]!;
    await latestTarget.getByRole('button', { name: 'Hamburger Menu', exact: true }).click();
    const menuRow = currentState.locator('.element-row').filter({ has: page.locator('.element-label', { hasText: /^Hamburger Menu$/ }) });
    await expect.poll(() => menuRow.locator('summary .state-chip').allTextContents(), { timeout: 5000 }).toContain('expanded');
    await currentState.locator('.element-label').filter({ hasText: /^All Items$/ }).waitFor({ state: 'visible' });
    await username.waitFor({ state: 'visible' });
    await password.waitFor({ state: 'visible' });
    expect(await currentState.locator('.collection-table tbody tr').count()).toBe(4);
    await page.screenshot({ path: '/tmp/nexus-semantic-ui.png', fullPage: true });
    expect(errors).toEqual([]);
  } finally { await uiBrowser.close(); await server.close(); await rm(directory, { recursive: true, force: true }); }
});
